#!/usr/bin/perl
# Generates shape/syllable_data.odin: the syllable state machines of the
# Indic, Khmer, Myanmar and Universal Shaping Engine shapers, and the vowel
# sequences that take a dotted circle, from HarfBuzz's source (its ragel
# machines as generated, and ms-use/IndicShapingInvalidCluster.txt).
#
#   perl tools/shape_unicode/gen_syllables.pl HARFBUZZ/src > shape/syllable_data.odin
#
# with HARFBUZZ the source of the HarfBuzz release shape/ is matched with
# (14.6.0).
use strict;
use warnings;
use Unicode::UCD qw(charscript prop_value_aliases);

my $hb = shift @ARGV or die "usage: gen_syllables.pl HARFBUZZ/src\n";

sub slurp {
	my ($path) = @_;
	open(my $fh, '<', $path) or die "$path: $!";
	local $/;
	my $text = <$fh>;
	close $fh;
	return $text;
}

sub rows {
	my ($per_line, @v) = @_;
	my $out = '';
	for (my $i = 0; $i < @v; $i += $per_line) {
		my $end = $i + $per_line - 1;
		$end = $#v if $end > $#v;
		$out .= "\t" . join(', ', @v[$i .. $end]) . ",\n";
	}
	return $out;
}

print "// Generated by tools/shape_unicode/gen_syllables.pl from HarfBuzz's syllable\n";
print "// machines and invalid vowel sequences (LICENSES/HarfBuzz-MIT.txt). Do not\n";
print "// edit.\n";
print "package shape\n\n";

my @ops = qw(None Te_Next Emit_Next Emit_Current Emit_Te Act Act_Switch);

for my $name (qw(indic khmer myanmar use)) {
	my $rl = slurp("$hb/hb-ot-shaper-$name-machine.rl");
	my $hh = slurp("$hb/hb-ot-shaper-$name-machine.hh");
	my $NAME = uc $name;
	my $m = "_${name}_syllable_machine";

	# Syllable types, in their enum's order.
	$rl =~ /enum\s+${name}_syllable_type_t\s*\{(.*?)\};/s or die "$name: no syllable types";
	my @types = map { s/^\s+|\s+$//gr } grep { /\S/ } split /,/, $1;
	my %type_index = map { $types[$_] => $_ } 0 .. $#types;
	print "// $name syllable types.\n";
	for my $i (0 .. $#types) {
		print uc($types[$i]), " :: $i\n";
	}
	print "\n";

	my %arrays;
	for my $a (qw(trans_keys key_spans index_offsets indicies trans_targs trans_actions to_state_actions from_state_actions eof_trans)) {
		$hh =~ /static const \w+(?: \w+)? ${m}_$a\[\] = \{(.*?)\};/s or die "$name: no $a";
		my @v = ($1 =~ /(-?\d+)/g);
		$arrays{$a} = \@v;
		print "\@(private, rodata)\n${NAME}_MACHINE_" . uc($a) . " := [" . scalar(@v) . "]i16 {\n" . rows(16, @v) . "}\n\n";
	}
	$hh =~ /static const int ${name}_syllable_machine_start = (\d+);/ or die "$name: no start";
	my $start = $1;

	# The state actions: which value sets ts to p, which clears it.
	$hh =~ /switch \( ${m}_from_state_actions\[cs\] \) \{\s*case (\d+):\s*(?:#line[^\n]*\n\s*)?\{ts = p;\}/s or die "$name: no from-state action";
	my $from_ts = $1;
	$hh =~ /switch \( ${m}_to_state_actions\[cs\] \) \{\s*case (\d+):\s*(?:#line[^\n]*\n\s*)?\{ts = 0;\}/s or die "$name: no to-state action";
	my $to_ts = $1;

	# The transition actions, each one of a few forms.
	$hh =~ /switch \( ${m}_trans_actions\[_trans\] \) \{(.*?)\n\t\}\n\n_again:/s or die "$name: no actions";
	my $body = $1;
	$body =~ s/^#line[^\n]*\n//mg;
	my (%action, %act_type);
	my $max_action = 0;
	my $max_act = 0;
	# The act switch first (its inner cases look like the outer ones),
	# then the top-level cases (each ends with a break at one tab).
	while ($body =~ s/\n\tcase (\d+):\n\t\{\tswitch\( act \) \{(.*?)\n\t\}\n\t\}\n\tbreak;//s) {
		my ($n, $acts) = ($1, $2);
		$max_action = $n if $n > $max_action;
		while ($acts =~ /case (\d+):\s*\{\{p = \(\(te\)\)-1;\} found_syllable \((\w+)\);/sg) {
			defined $type_index{$2} or die "$name: unknown syllable type $2";
			$act_type{$1} = $type_index{$2};
			$max_act = $1 if $1 > $max_act;
		}
		$action{$n} = ['Act_Switch', 0];
	}
	while ($body =~ /\n\tcase (\d+):\n(.*?)\n\tbreak;/sg) {
		my ($n, $code) = ($1, $2);
		$max_action = $n if $n > $max_action;
		my $type = sub {
			my ($t) = @_;
			defined $type_index{$t} or die "$name: unknown syllable type $t";
			return $type_index{$t};
		};
		if ($code =~ /^\s*\{te = p\+1;\}\s*\{act = (\d+);\}\s*$/s) {
			$action{$n} = ['Act', $1];
			$max_act = $1 if $1 > $max_act;
		} elsif ($code =~ /^\s*\{te = p\+1;\}\s*$/s) {
			$action{$n} = ['Te_Next', 0];
		} elsif ($code =~ /^\s*\{te = p\+1;\{ found_syllable \((\w+)\);[^}]*\}\}\s*$/s) {
			$action{$n} = ['Emit_Next', $type->($1)];
		} elsif ($code =~ /^\s*\{te = p;p--;\{ found_syllable \((\w+)\);[^}]*\}\}\s*$/s) {
			$action{$n} = ['Emit_Current', $type->($1)];
		} elsif ($code =~ /^\s*\{\{p = \(\(te\)\)-1;\}\{ found_syllable \((\w+)\);[^}]*\}\}\s*$/s) {
			$action{$n} = ['Emit_Te', $type->($1)];
		} else {
			die "$name: action $n not understood:\n$code\n";
		}
	}
	print "\@(private, rodata)\n${NAME}_MACHINE_ACTIONS := [" . ($max_action + 1) . "]Machine_Action {\n";
	for my $n (0 .. $max_action) {
		my ($op, $arg) = @{$action{$n} // ['None', 0]};
		print "\t{.$op, $arg},\n";
	}
	print "}\n\n";
	print "\@(private, rodata)\n${NAME}_MACHINE_ACT_TYPES := [" . ($max_act + 1) . "]i8 {" . join(', ', map { $act_type{$_} // -1 } 0 .. $max_act) . "}\n\n";
	print "\@(private)\n${NAME}_MACHINE := Machine {\n";
	for my $a (qw(trans_keys key_spans index_offsets indicies trans_targs trans_actions to_state_actions from_state_actions eof_trans)) {
		print "\t$a = ${NAME}_MACHINE_" . uc($a) . "[:],\n";
	}
	print "\tactions = ${NAME}_MACHINE_ACTIONS[:],\n";
	print "\tact_types = ${NAME}_MACHINE_ACT_TYPES[:],\n";
	print "\tstart = $start,\n\tfrom_ts = $from_ts,\n\tto_ts = $to_ts,\n";
	my $broken = $type_index{"${name}_broken_cluster"} // die "$name: no broken cluster type";
	print "\tbroken = $broken,\n}\n\n";
}

# Vowel sequences that render as another vowel: a dotted circle goes
# before their last character (the script is the first character's).
{
	my $text = slurp("$hb/ms-use/IndicShapingInvalidCluster.txt");
	my @seqs;
	for my $line (split /\n/, $text) {
		$line =~ s/#.*//;
		next unless $line =~ /^\s*([0-9A-F ]+?)\s*;/;
		my @cps = map { hex } split ' ', $1;
		die "sequence of " . scalar(@cps) . ": $line" if @cps < 2 || @cps > 3;
		my $script = charscript($cps[0]);
		push @seqs, [$script, @cps, (0) x (3 - @cps)];
	}
	@seqs = sort { $a->[0] cmp $b->[0] || $a->[1] <=> $b->[1] || $a->[2] <=> $b->[2] || $a->[3] <=> $b->[3] } @seqs;
	print "// Vowel sequences that look like another vowel (a dotted circle goes\n";
	print "// before the last character): script, two or three characters (0 for\n";
	print "// none); sorted.\n";
	print "\@(private, rodata)\nVOWEL_CONSTRAINTS := [" . scalar(@seqs) . "]Vowel_Constraint {\n";
	for my $s (@seqs) {
		printf "\t{.%s, {0x%04X, 0x%04X, 0x%04X}},\n", @$s;
	}
	print "}\n";
}
